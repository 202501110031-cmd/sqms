export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => localStorage.getItem('sqms_language') || 'en');
  const setLanguage = (value) => {
    if (!messages[value]) return;
    localStorage.setItem('sqms_language', value);
    setLanguageState(value);
  };

  const value = useMemo(() => {
    const dictionary = messages[language] || messages.en;
    const t = (key, variables = {}) => {
      let text = dictionary[key] || messages.en[key] || key;
      for (const [name, replacement] of Object.entries(variables)) {
        text = text.replaceAll(`{${name}}`, replacement);
      }
      return text;
    };
    return { language, setLanguage, t };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}

export function localDepartmentName(department, language) {
  if (!department) return '';
  if (language === 'mr') return department.nameMr || department.name_mr || department.name;
  if (language === 'hi') return department.nameHi || department.name_hi || department.name;
  return department.name;
}
